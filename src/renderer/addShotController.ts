// Reuse the presentation algorithm with operation-local state: it prepares new-shot assets
// but cannot publish history, busy state or project changes into the active workspace.
export const prepareAddShotMatte = async (
  baseProject: Project,
  mode: "expanded" | "embedded",
  shotIds: readonly string[],
  request: { origin: AddShotWorkspace; isCurrent: () => boolean; setStatus: (status: string) => void; dialogueOverlayEnabled: boolean; api?: Window["storyboard"] },
  dependencies: {
    api: Window["storyboard"];
    queue: BitmapLayerWriteQueue;
    canvas?: Pick<Parameters<typeof createShotPresentationController>[0], "expandBitmapLayer" | "createMatteOverlay" | "createDialogueOverlay">;
  }
): Promise<Project | undefined> => {
  const { origin, isCurrent } = request;
  if (!isCurrent() || !origin.folderPath || !origin.metadataPath) return;
  const check = () => { if (!isCurrent()) throw new Error("Add shot workspace changed"); };
  const { api } = dependencies;
  const localProjectRef = { current: { ...baseProject, shots: baseProject.shots.filter((shot) => shotIds.includes(shot.id)) } };

  const scopedApi = {
    ...api,
    ensureLayerAssets: async (payload: Parameters<typeof api.ensureLayerAssets>[0]) => {
      check();
      const result = await api.ensureLayerAssets(payload);
      check();
      return result;
    },
    readLayerPng: async (payload: Parameters<typeof api.readLayerPng>[0]) => {
      check();
      const result = await api.readLayerPng(payload);
      check();
      return result;
    },
    writeLayerPng: async (payload: Parameters<typeof api.writeLayerPng>[0]) => {
      check();
      // New system-layer paths are generated by the existing presentation algorithm.
      const result = await api.writeLayerPng(payload);
      check();
      return result;
    },
    deleteLayerPng: async () => {
      // TODO: retain provisional assets, including missing-at-snapshot system PNGs.
      throw new Error("Provisional Add shot assets retained; owned cleanup is not available");
    }
  };
  const controller = createShotPresentationController({
    ...dependencies.canvas,
    api: scopedApi,
    bitmapLayerWriteQueueRef: { current: dependencies.queue },
    createHistoryEntry: async (paths = []) => ({
      project: localProjectRef.current,
      fileNameSyncState: "unsynced",
      selectedShotIds: [],
      layerAssets: await readLayerAssetSnapshots(scopedApi, origin.folderPath!, paths)
    }),
    folderPath: origin.folderPath,
    metadataPath: origin.metadataPath,
    projectRef: localProjectRef,
    shotPresentationActionRef: { current: undefined },
    markShotsDirty: () => undefined,
    recordUndoEntry: () => undefined,
    setStatus: (status) => { if (isCurrent()) request.setStatus(status); },
    updateProject: (update) => {
      check();
      localProjectRef.current = typeof update === "function" ? update(localProjectRef.current) : update;
    }
  });
  const inherited = await controller.handleInheritSceneMatte(localProjectRef.current, mode, shotIds, {
    dialogueOverlayEnabled: request.dialogueOverlayEnabled
  });
  return isCurrent() && inherited ? localProjectRef.current : undefined;
};

type ProjectUpdate = Project | ((currentProject: Project) => Project);
type StoryboardApi = Window["storyboard"] | undefined;

export type AddShotWorkspace = {
  identity: object;
  folderPath: string | undefined;
  metadataPath: string | undefined;
};

// A per-Add operation handle returned by the owner. The caller keeps it locally and uses its
// bound api for every effect, so an interleaved newer Add cannot replace it.
export type AddShotOperation = {
  api: Window["storyboard"];
  registerBlankShot: (done: { shotId: string }) => void;
};

export type InitialAddShotContext =
  | {
      kind: "ready";
      baseProject: Project;
      insertAfterShotId: string | undefined;
      targetFolderPath: string;
    }
  | {
      kind: "needs-folder";
      status: "Choose a folder for the first shot";
    };

export const initialAddShotContext = ({
  folderPath,
  metadataPath,
  primarySelectedShotId,
  project
}: {
  folderPath: string | undefined;
  metadataPath: string | undefined;
  primarySelectedShotId: string | undefined;
  project: Project;
}): InitialAddShotContext =>
  folderPath && metadataPath
    ? {
        kind: "ready",
        baseProject: project,
        insertAfterShotId: primarySelectedShotId,
        targetFolderPath: folderPath
      }
    : {
        kind: "needs-folder",
        status: "Choose a folder for the first shot"
      };

export const addShotInsertedShotId = (
  project: Project,
  imagePath: string
): string | undefined => project.shots.find((shot) => shot.imagePath === imagePath)?.id;

export const useAddShotController = ({
  beginAddShotOperation,
  isImageImportLocked,
  api,
  blankShotPreset,
  captureWorkspace,
  isCurrentWorkspace,
  createTransparentLayerDataUrl,
  folderPath,
  loadFolderScan,
  inheritSceneMatte,
  markShotsDirty,
  metadataPath,
  openOwnedFolder,
  primarySelectedShotId,
  projectRef,
  selectSingleShot,
  setRecentFolders,
  setStatus,
  setWorkspaceTask,
  updateProject,
  publishNewShot
}: {
  beginAddShotOperation?: () => AddShotOperation | undefined;
  isImageImportLocked: () => boolean;
  api: StoryboardApi;
  blankShotPreset: BlankShotPreset;
  captureWorkspace: () => AddShotWorkspace;
  isCurrentWorkspace: (request: AddShotWorkspace) => boolean;
  createTransparentLayerDataUrl: (width: number, height: number) => Promise<string>;
  folderPath: string | undefined;
  loadFolderScan: (
    scan: FolderScanPayload,
    nextStatus: string,
    dirty?: boolean,
    resetDirtyShots?: boolean,
    clearRecoveryRequired?: boolean
  ) => Promise<Project | undefined>;
  inheritSceneMatte: (
    baseProject: Project,
    mode: "expanded" | "embedded",
    shotIds: readonly string[],
    request: { origin: AddShotWorkspace; isCurrent: () => boolean; setStatus: (status: string) => void; dialogueOverlayEnabled: boolean; api?: Window["storyboard"] }
  ) => Promise<Project | undefined>;
  markShotsDirty: (shotIds: string[]) => void;
  metadataPath: string | undefined;
  // Owned normal open (readonly discovery + preview phase + current load) for the first
  // shot's folder; absent keeps the legacy raw open branch. The result is bound to the
  // identity set by THIS load plus whether the whole load (incl. auto-import/migration)
  // completed; the caller must not re-capture an unrelated workspace identity.
  openOwnedFolder?: (folderPath: string) => Promise<AddShotWorkspace & { project?: Project; loaded: boolean } | undefined>;
  primarySelectedShotId: string | undefined;
  projectRef: { current: Project };
  selectSingleShot: (shotId: string | undefined) => void;
  setRecentFolders: (folders: string[]) => void;
  setStatus: (status: string) => void;
  setWorkspaceTask: (task: WorkspaceTask | undefined) => void;
  updateProject: (projectUpdate: ProjectUpdate, markFileNamesUnsynced?: boolean, recordUndo?: boolean) => void;
  publishNewShot?: (update: (p: Project) => Project, shotId: string, isCurrent: () => boolean) => Promise<boolean>;
}) => {
  const handleAddShot = async () => {
    if (isImageImportLocked()) return;
    let origin = captureWorkspace();
    const isCurrent = () => isCurrentWorkspace(origin);
    const reportStatus = (message: string) => {
      if (isCurrent()) setStatus(message);
    };
    if (origin.folderPath !== folderPath || origin.metadataPath !== metadataPath) return;
    if (!api) {
      setStatus("Cannot add shot: Electron preload API is unavailable");
      return;
    }

    let context = initialAddShotContext({
      folderPath,
      metadataPath,
      primarySelectedShotId,
      project: projectRef.current
    });

    if (context.kind === "needs-folder") {
      setStatus(context.status);
      const selectedFolder = await withStatus(
        "Choose folder failed",
        () => api.selectFolder(),
        reportStatus
      );
      if (!isCurrent()) return;
      if (!selectedFolder) {
        setStatus("Add shot cancelled");
        return;
      }

      setWorkspaceTask({
        kind: "open",
        label: "Loading folder...",
        current: 0,
        total: 0
      });

      // No automatic recovery here. When the owned open is available it runs the existing
      // readonly discovery + preview phase + current load in one place, so this branch
      // never double-loads the folder or bypasses the owned admission with a raw open.
      let opened: { folderPath: string; metadataPath: string; project?: Project } | undefined;
      if (openOwnedFolder) {
        const owned = await withStatus("Open folder failed", () => openOwnedFolder(selectedFolder), reportStatus);
        // Adopt only a fully completed load, bound to the identity set by THIS load, so an
        // interleaved same-folder load cannot let this Add continue on a newer workspace.
        if (!owned || !owned.loaded || !owned.folderPath || !owned.metadataPath) {
          setWorkspaceTask(undefined);
          return;
        }
        origin = { identity: owned.identity, folderPath: owned.folderPath, metadataPath: owned.metadataPath };
        opened = { folderPath: owned.folderPath, metadataPath: owned.metadataPath, project: owned.project };
      } else {
        const scan = await withStatus(
          "Open folder failed",
          () => api.openFolderByPath(selectedFolder),
          reportStatus
        );
        if (!isCurrent()) return;
        if (!scan) {
          setWorkspaceTask(undefined);
          return;
        }
        const loadingProject = loadFolderScan(scan, "Folder opened", !scan.project, true, true);
        // loadFolderScan invalidates identity synchronously; adopt only that invocation's
        // generation, not whichever workspace happens to be active after its awaits.
        origin = captureWorkspace();
        const loadedProject = await loadingProject;
        opened = { folderPath: scan.folderPath, metadataPath: scan.metadataPath, project: loadedProject ?? projectRef.current };
      }

      setWorkspaceTask(undefined);
      if (!isCurrent() || !opened) return;
      if (origin.folderPath !== opened.folderPath || origin.metadataPath !== opened.metadataPath) return;
      const baseProject = opened.project ?? projectRef.current;
      context = {
        kind: "ready",
        targetFolderPath: opened.folderPath,
        baseProject,
        insertAfterShotId: baseProject.shots[0]?.id
      };
      void api.getRecentFolders().then((folders) => {
        if (isCurrent()) setRecentFolders(folders);
      }).catch(() => undefined);
    }

    // Blank TIFF creation is the first irreversible effect; once admitted, finish
    // its assets + metadata even if the image lock changes. Workspace identity still applies.
    if (isImageImportLocked()) return;
    // Capture THIS Add's own operation handle (never a shared latest ref) against the
    // workspace actually being produced; every following effect uses its bound api.
    const operation = beginAddShotOperation?.();
    const effectApi = operation?.api ?? api;
    const image = await withStatus(
      "Add shot failed",
      () => effectApi.createBlankShot(context.targetFolderPath, { preset: blankShotPreset }),
      reportStatus
    );

    if (!isCurrent() || !image) {
      return;
    }

    const projectAtInsert = projectRef.current;
    let nextProject = addGeneratedShot(
      projectAtInsert,
      image as ImportedImage,
      context.insertAfterShotId
    );
    const nextShotId = addShotInsertedShotId(nextProject, image.imagePath);
    const nextShot = nextShotId
      ? nextProject.shots.find((shot) => shot.id === nextShotId)
      : undefined;
    if (nextShotId) {
      // Register THIS Add's own recorded blank completion (never a caller-supplied path) inside the
      // operation's scope error handling: a refusal — the owner became loading/held-receipt during
      // the blank await, or no completion was recorded — must not surface as an unhandled rejection,
      // and provisional assets are kept (no cleanup, no new UI pollution).
      const registered = await withStatus(
        "Add shot failed",
        async () => {
          operation?.registerBlankShot({ shotId: nextShotId });
          return true;
        },
        reportStatus
      );
      if (operation && !registered) return;
    }
    if (nextShot) {
      const didCreateLayerAssets = await withStatus(
        "Add shot layer failed",
        async () => {
          await Promise.all(
            generatedShotTransparentLayerAssets(nextShot).map(async (layer) => {
              const dataUrl = await createTransparentLayerDataUrl(layer.width, layer.height);
              if (!isCurrent()) return;
              await effectApi.writeLayerPng({
                folderPath: context.targetFolderPath,
                bitmapPath: layer.bitmapPath,
                dataUrl
              });
              if (!isCurrent()) return;
            })
          );
          return true;
        },
        reportStatus
      );
      if (!isCurrent() || !didCreateLayerAssets) {
        return;
      }
    }

    if (!nextShot || !nextShotId || !isCurrent()) return;
    if (operation) {
      // Normal pending persistence validates every referenced PNG before it can
      // autosave. Prepare the image raster while this Add still owns its blank
      // completion; the bound API admits only this registered shot, not existing
      // shots. This ensure operation does not publish JSON or certify output.
      const preparedAssets = await withStatus("Add shot layer failed", async () => {
        await effectApi.ensureLayerAssets({
          folderPath: context.targetFolderPath,
          metadataPath: origin.metadataPath!,
          project: { ...nextProject, shots: [nextShot], parkedShots: [] }
        });
        return true;
      }, reportStatus);
      if (!isCurrent() || !preparedAssets) return;
    }
    const insertShot = (latestProject: Project, shot: typeof nextShot): Project => {
      const orderedShots = sortedShots(latestProject.shots);
      const selectedIndex = context.insertAfterShotId
        ? orderedShots.findIndex((item) => item.id === context.insertAfterShotId)
        : -1;
      orderedShots.splice(selectedIndex === -1 ? orderedShots.length : selectedIndex + 1, 0, shot);
      return {
        ...latestProject,
        shots: orderedShots.map((item, order) => ({ ...item, order })),
        updatedAt: new Date().toISOString()
      };
    };
    const sceneProject = projectRef.current;
    // Capture scene settings before the candidate includes the unconfigured new shot.
    const dialogueOverlayEnabled = sceneDialogueOverlayEnabledForProject(sceneProject);
    nextProject = insertShot(sceneProject, nextShot);
    let preparedShot = nextShot;
    const inheritedMatteMode = sceneMatteModeForProject(sceneProject);
    if (inheritedMatteMode) {
      // Preparation must not publish project/history/selection. Only this controller commits.
      const inherited = await withStatus("Add shot matte failed", () => inheritSceneMatte(
        nextProject,
        inheritedMatteMode,
        [nextShotId],
        { origin, isCurrent, setStatus: reportStatus, dialogueOverlayEnabled, api: effectApi }
      ), reportStatus);
      if (!isCurrent() || !inherited) return;
      const inheritedShot = inherited.shots.find((shot) => shot.id === nextShotId);
      if (!inheritedShot) return;
      preparedShot = inheritedShot;
    }
    // TODO: provisional TIFF/preview/PNG assets remain in the origin on failure/staleness.
    // No safe owned-asset cleanup port exists; never delete files based on live JSON references.
    if (!isCurrent()) return;
    if (publishNewShot) {
      if (!await publishNewShot(currentProject => insertShot(currentProject, preparedShot), nextShotId, isCurrent)) {
        reportStatus("Add shot incomplete; output initialization refused");
        return;
      }
    } else {
      updateProject((currentProject) => isCurrent() ? insertShot(currentProject, preparedShot) : currentProject, true, false);
    }
    if (!isCurrent()) return;
    markShotsDirty([nextShotId]);
    selectSingleShot(nextShotId);
    setStatus(`Added ${blankShotPreset} shot: ${image.fileName}`);
  };

  return { handleAddShot };
};
